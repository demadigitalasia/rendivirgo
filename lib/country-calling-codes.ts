export function countryFlagEmoji(regionCode: string): string {
  const code = regionCode.toUpperCase();
  if (!/^[A-Z]{2}$/.test(code)) return "";
  return String.fromCodePoint(...[...code].map((letter) => letter.charCodeAt(0) + 127397));
}

export function internationalPhoneNumber(regionCode: string, nationalNumber: string): string {
  const region = regionCode.toUpperCase();
  const callingCode = COUNTRY_CALLING_CODES[region];
  if (!callingCode) return "";
  let digits = nationalNumber.replace(/\D/g, "");
  const nationalPrefix = COUNTRY_NATIONAL_PREFIXES[region];
  if (nationalPrefix && digits.startsWith(nationalPrefix) && digits.length > nationalPrefix.length + 5) {
    digits = digits.slice(nationalPrefix.length);
  }
  return digits ? "+" + callingCode + digits : "";
}
